static string LowerFirst(string value)
{
	if (string.IsNullOrEmpty(value))
	{
		return value;
	}

	return char.ToLowerInvariant(value[0]) + value[1..];
}

static string ToPascal(string value)
{
	if (string.IsNullOrEmpty(value))
	{
		return value;
	}

	return char.ToUpperInvariant(value[0]) + value[1..];
}

static string ShortType(string value)
{
	var index = value.LastIndexOf('.');
	return index < 0 ? value : value[(index + 1)..];
}

internal sealed record ProtoMethod(string RpcMethodName, string HandlerName, string InputType, string OutputType);
